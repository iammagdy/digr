CREATE SCHEMA IF NOT EXISTS auth;
CREATE TABLE auth.users (id uuid PRIMARY KEY);

CREATE TABLE public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE RESTRICT,
  email text, sender_name text, sender_phone text, deletion_scheduled_for timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.settings_public (key text PRIMARY KEY, value jsonb);

CREATE TABLE public.topups (
  id text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  amount_egp numeric NOT NULL,
  reference text NOT NULL UNIQUE,
  sender_name text NOT NULL, sender_phone text NOT NULL, receipt_file_id text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_topups_amount_positive CHECK (amount_egp > 0),
  CONSTRAINT chk_topups_status CHECK (status = ANY (ARRAY['pending','approved','rejected']))
);

CREATE TABLE public.jobs (
  id text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  status text NOT NULL,
  endpoint_id text, target_volume_min integer, target_volume_max integer,
  reserved_credits numeric, charged_credits numeric,
  delivered_units integer DEFAULT 0,
  current_cursor text,
  accumulated_cost_usd numeric DEFAULT 0,
  attempt_count integer DEFAULT 0,
  result_file_id text, error_message text,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  next_attempt_at timestamptz DEFAULT timezone('utc'::text, now()),
  step integer DEFAULT 0,
  lease_until timestamptz,
  unit_price numeric,
  CONSTRAINT chk_jobs_status CHECK (status = ANY (ARRAY['queued','running','completed','failed','refused'])),
  CONSTRAINT chk_jobs_unit_price_positive CHECK (unit_price IS NULL OR unit_price > 0)
);
CREATE INDEX idx_jobs_lease_until ON public.jobs (lease_until);
CREATE INDEX idx_jobs_status ON public.jobs (status);
CREATE INDEX idx_jobs_status_next_attempt ON public.jobs (status, next_attempt_at);
CREATE INDEX idx_jobs_user_id ON public.jobs (user_id);

CREATE TABLE public.plans_quotes (
  id text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  quote_hash text NOT NULL,
  status text NOT NULL DEFAULT 'quoted',
  items jsonb NOT NULL,
  total_reserved_credits numeric NOT NULL,
  output_formats jsonb,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_quotes_status CHECK (status = ANY (ARRAY['quoted','accepted','expired','refused']))
);
CREATE INDEX idx_plans_quotes_hash ON public.plans_quotes (quote_hash);
CREATE INDEX idx_plans_quotes_user_id ON public.plans_quotes (user_id);

CREATE TABLE public.job_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id text NOT NULL REFERENCES public.jobs(id) ON DELETE RESTRICT,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  message text NOT NULL, units integer DEFAULT 0, event_type text DEFAULT 'progress',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.provider_costs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id text REFERENCES public.jobs(id) ON DELETE RESTRICT,
  provider text NOT NULL, units integer DEFAULT 1, cost_usd numeric NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(), is_estimate boolean DEFAULT false
);
CREATE INDEX idx_provider_costs_created_at_cost ON public.provider_costs (created_at, cost_usd);
CREATE INDEX idx_provider_costs_job_id ON public.provider_costs (job_id);

CREATE TABLE public.credit_ledger (
  id text PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE RESTRICT,
  delta numeric NOT NULL,
  type text NOT NULL,
  job_id text, topup_id text, note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chk_ledger_delta_direction CHECK (
    ((type = ANY (ARRAY['reserve','charge'])) AND (delta < 0)) OR
    ((type = ANY (ARRAY['release','topup','grant','goodwill'])) AND (delta > 0))),
  CONSTRAINT chk_ledger_type CHECK (type = ANY (ARRAY['reserve','release','charge','topup','grant','goodwill']))
);
CREATE INDEX idx_credit_ledger_job_id ON public.credit_ledger (job_id);
CREATE INDEX idx_credit_ledger_topup_id ON public.credit_ledger (topup_id);
CREATE INDEX idx_credit_ledger_user_id ON public.credit_ledger (user_id);

CREATE TABLE public.credit_ledger_kinds (
  ledger_id text PRIMARY KEY REFERENCES public.credit_ledger(id) ON DELETE RESTRICT,
  kind text NOT NULL, actor_id uuid REFERENCES auth.users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT credit_ledger_kinds_kind_check CHECK (kind = ANY (ARRAY['topup_instapay','promo_code','admin_grant']))
);
