import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadProviderTabState } from "../src/lib/server/providerKeyAdmin";
import { __setProviderKeyStoreForTests, resetProviderKeyCache } from "../src/lib/server/providerKeys";
import { invalidateProviderStatusCache } from "../src/lib/server/providerStatus";
import { flushProviderLimitsCache } from "../src/lib/server/providerLimits";
import { mockProviderFetch } from "./helpers/providerKeyTestKit";

/**
 * The TREG tab must be byte-for-byte what main produces. `tests/fixtures/treg-tab-state.main.json` was generated by the code of
 * origin/main (before the multi-provider change) against this exact fake database and fake provider; this test compares the
 * current code with it. Generate again only from main: GENERATE_GOLDEN=1 npx vitest run tests/multi-provider-treg-unchanged.test.ts
 */
const GOLDEN = path.join(__dirname, "fixtures", "treg-tab-state.main.json");

const costRows = [
  { job_id: "job_abcdef12345678", units: 3, cost_usd: 0.0123, created_at: "2026-10-22T08:00:00.000Z", is_estimate: false },
  { job_id: "job_zzzz99999999", units: 0, cost_usd: 0.05, created_at: "2026-10-22T07:00:00.000Z", is_estimate: true },
  { job_id: null, units: 1, cost_usd: 0.001, created_at: "2026-10-21T07:00:00.000Z", is_estimate: false },
];

function fakeClient() {
  const settings: Record<string, any> = { provider_limits: { dailyUsd: 0.8, warnPercent: 80 }, provider_keys: { lowBalanceThresholdUsd: 0.2, tregOrgId: "org_1" } };
  const make = (table: string) => {
    const filters: Array<[string, any]> = [];
    const c: any = {
      select: () => c,
      eq: (col: string, val: any) => { filters.push([col, val]); return c; },
      gte: () => c, order: () => c, limit: () => c, in: () => c,
      maybeSingle: async () => {
        if (table === "settings_private") { const k = filters.find(([col]) => col === "key")?.[1]; return { data: k in settings ? { value: settings[k] } : null, error: null }; }
        if (table === "provider_api_keys") return { data: { active_last4: "7890", active_set_at: "2026-10-20T00:00:00.000Z", previous_last4: "1111", previous_set_at: "2026-10-19T00:00:00.000Z", version: 3 }, error: null };
        return { data: null, error: null };
      },
      then: (resolve: any) => resolve({ data: table === "provider_costs" ? costRows : [], error: null }),
    };
    return c;
  };
  return { from: make };
}

describe("TREG tab output is unchanged versus main", () => {
  beforeEach(() => {
    vi.useFakeTimers();
    vi.setSystemTime(new Date("2026-10-22T09:30:00.000Z"));
    process.env.TREG_TOKEN = "testonly-treg-token-1234567890";
    delete process.env.PROVIDER_KEYS_ENCRYPTION_KEY;
    __setProviderKeyStoreForTests(null);
    resetProviderKeyCache(); invalidateProviderStatusCache(); flushProviderLimitsCache();
  });
  afterEach(() => { vi.useRealTimers(); delete process.env.TREG_TOKEN; });

  it("loadProviderTabState('treg') equals the snapshot generated from main", async () => {
    const { fn } = mockProviderFetch((url) => {
      if (url.endsWith("/auth/me")) return { status: 200, body: { email: "owner@example.com", org_id: "org_1" } };
      if (url.includes("/balance")) return { status: 200, body: { balance_micro: 1234567, held_micro: 1000 } };
      return { status: 404 };
    });
    const state = await loadProviderTabState({ client: fakeClient(), fetchFn: fn, now: () => Date.now() }, "treg", { forceRefresh: true });
    const actual = JSON.parse(JSON.stringify(state));
    if (process.env.GENERATE_GOLDEN === "1") writeFileSync(GOLDEN, JSON.stringify(actual, null, 2) + "\n");
    expect(existsSync(GOLDEN)).toBe(true);
    expect(actual).toEqual(JSON.parse(readFileSync(GOLDEN, "utf8")));
    // a few facts, so the snapshot cannot silently be an empty shell
    expect(actual.provider).toBe("treg");
    expect(actual.status.balance.balanceUsd).toBe(1.234567);
    expect(actual.spend.capUsd).toBe(0.8);
    expect(actual.activity).toHaveLength(3);
    expect(actual.accountEmail).toBe("owner@example.com");
  });
});
