/**
 * Builds the SQL proposal files for raising the per-job points cap from 600 to 5000 from the saved PRODUCTION definitions
 * (docs/proposals/prod-definitions/). Deterministic: the same input gives the same files, and tests/job-cap-proposal.test.ts
 * regenerates them and fails if the committed files drift or if any line outside the intended ones changes.
 * It writes files only. It never connects to a database and nothing it writes is applied anywhere.
 *
 *   npx tsx scripts/proposals/buildJobCapProposal.ts
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

export const NEW_CAP = 5000;
export const NEW_VOLUME_CEILING = 100_000;
const ROOT = path.resolve(__dirname, "..", "..");
const DEFS = path.join(ROOT, "docs", "proposals", "prod-definitions");
export const OUT = path.join(ROOT, "docs", "proposals", "job-cap-5000");

interface Edit { from: string; to: string }
interface FnSpec { file: string; name: string; signature: string; optionA: Edit[]; optionB: Edit[] }

export const FUNCTIONS: FnSpec[] = [
  {
    file: "settle_people_job_atomic.sql", name: "settle_people_job_atomic",
    signature: "public.settle_people_job_atomic(text, integer, integer, integer, numeric, text)",
    optionA: [
      { from: "p_points_cap numeric DEFAULT 600,", to: `p_points_cap numeric DEFAULT ${NEW_CAP},` },
      { from: "COALESCE(p_points_cap,600), 600);", to: `COALESCE(p_points_cap,${NEW_CAP}), ${NEW_CAP});` },
    ],
    optionB: [
      { from: "p_points_cap numeric DEFAULT 600,", to: "p_points_cap numeric DEFAULT public.job_points_cap()," },
      { from: "COALESCE(p_points_cap,600), 600);", to: "COALESCE(p_points_cap,public.job_points_cap()), public.job_points_cap());" },
    ],
  },
  {
    file: "settle_job_atomic.sql", name: "settle_job_atomic",
    signature: "public.settle_job_atomic(text, numeric, text)",
    optionA: [{ from: "p_points_cap numeric DEFAULT 600,", to: `p_points_cap numeric DEFAULT ${NEW_CAP},` }],
    optionB: [{ from: "p_points_cap numeric DEFAULT 600,", to: "p_points_cap numeric DEFAULT public.job_points_cap()," }],
  },
  {
    // Not a points cap: the RECORD ceiling of one job. With a 5000-point cap and a cheap per-record price (0.28 points) a job holds
    // about 15,000 records, so a ceiling of 5000 records would refuse it. Separate step, separate rollback.
    file: "accept_quote_atomic.sql", name: "accept_quote_atomic",
    signature: "public.accept_quote_atomic(text, uuid, text)",
    optionA: [{ from: "v_target_max > 5000 THEN", to: `v_target_max > ${NEW_VOLUME_CEILING} THEN` }],
    optionB: [{ from: "v_target_max > 5000 THEN", to: `v_target_max > ${NEW_VOLUME_CEILING} THEN` }],
  },
  {
    file: "create_quote_atomic.sql", name: "create_quote_atomic",
    signature: "public.create_quote_atomic(uuid, text, text, jsonb, numeric, text[], timestamp with time zone, text[])",
    optionA: [{ from: "  v_cap numeric := 600;", to: `  v_cap numeric := ${NEW_CAP};` }],
    optionB: [{ from: "  v_cap numeric := 600;", to: "  v_cap numeric := public.job_points_cap();" }],
  },
];

export const HELPER_SQL = `CREATE OR REPLACE FUNCTION public.job_points_cap()
 RETURNS numeric
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public', 'pg_temp'
AS $function$ SELECT ${NEW_CAP}::numeric $function$;`;

const read = (f: string) => readFileSync(path.join(DEFS, f), "utf8");
const body = (text: string) => text.split("\n").filter((l) => !l.startsWith("-- PRODUCTION definition")).join("\n").trim().replace(/;?$/, ";");

function applyEdits(text: string, edits: Edit[]): string {
  let out = text;
  for (const e of edits) {
    const count = out.split(e.from).length - 1;
    if (count !== 1) throw new Error(`expected exactly one occurrence of ${JSON.stringify(e.from)}, found ${count}`);
    out = out.replace(e.from, e.to);
  }
  return out;
}

const grants = (signature: string) =>
  `REVOKE ALL ON FUNCTION ${signature} FROM PUBLIC, anon, authenticated;\nGRANT EXECUTE ON FUNCTION ${signature} TO service_role;`;

export function buildFiles(): Record<string, string> {
  const files: Record<string, string> = {};
  const header = (what: string) => `-- ${what}\n-- PROPOSAL. NOT applied. Generated by scripts/proposals/buildJobCapProposal.ts from the production definitions read on 2026-10-21.\n-- Paste into the Supabase SQL editor only after the owner has approved G-MONEY.\n`;
  const order: string[] = [];
  let n = 0;
  for (const option of ["a", "b"] as const) {
    const dir = `option-${option}`;
    if (option === "b") {
      n += 1;
      const helperName = `step0_job_points_cap_helper.sql`;
      files[`${dir}/${helperName}`] = `${header("Option B, step 0: one helper that holds the per-job points cap (every function below calls it)")}BEGIN;\n${HELPER_SQL}\n${grants("public.job_points_cap()")}\nCOMMIT;\n`;
      files[`${dir}/rollback_step0_job_points_cap_helper.sql`] = `${header("Option B rollback of step 0 (run LAST, after the function rollbacks)")}BEGIN;\nDROP FUNCTION IF EXISTS public.job_points_cap();\nCOMMIT;\n`;
    }
    FUNCTIONS.forEach((fn, i) => {
      const edits = option === "a" ? fn.optionA : fn.optionB;
      const original = body(read(fn.file));
      const changed = applyEdits(original, edits);
      const tag = `step${i + 1}_${fn.name}`;
      files[`${dir}/${tag}.sql`] = `${header(`Option ${option.toUpperCase()}, step ${i + 1}: ${fn.name}`)}BEGIN;\n${changed}\n${grants(fn.signature)}\nCOMMIT;\n`;
      files[`${dir}/rollback_${tag}.sql`] = `${header(`Option ${option.toUpperCase()} rollback of step ${i + 1}: restores the production body of ${fn.name} exactly`)}BEGIN;\n${original}\n${grants(fn.signature)}\nCOMMIT;\n`;
      files[option === "a" ? `functions/${fn.file}` : `functions-b/${fn.file}`] = `${changed}\n`;
    });
    order.push(dir);
  }
  void order;
  return files;
}

export function unifiedDiff(a: string, b: string, label: string): string {
  const al = a.split("\n");
  const bl = b.split("\n");
  const out: string[] = [`--- production/${label}`, `+++ proposed/${label}`];
  for (let i = 0; i < Math.max(al.length, bl.length); i += 1) {
    if (al[i] === bl[i]) continue;
    if (al[i] !== undefined) out.push(`@@ line ${i + 1} @@`, `-${al[i]}`);
    if (bl[i] !== undefined) out.push(`+${bl[i]}`);
  }
  return out.join("\n");
}

export function buildDiffs(): Record<string, string> {
  const diffs: Record<string, string> = {};
  for (const option of ["a", "b"] as const) {
    const parts: string[] = [];
    for (const fn of FUNCTIONS) {
      const edits = option === "a" ? fn.optionA : fn.optionB;
      const original = body(read(fn.file));
      parts.push(unifiedDiff(original, applyEdits(original, edits), fn.file));
    }
    if (option === "b") parts.unshift(`+++ new object (option B only)\n+${HELPER_SQL.split("\n").join("\n+")}`);
    diffs[`diffs/option-${option}.diff`] = `${parts.join("\n\n")}\n`;
  }
  return diffs;
}

export function writeAll(): void {
  rmSync(path.join(OUT, "option-a"), { recursive: true, force: true });
  rmSync(path.join(OUT, "option-b"), { recursive: true, force: true });
  rmSync(path.join(OUT, "functions"), { recursive: true, force: true });
  rmSync(path.join(OUT, "functions-b"), { recursive: true, force: true });
  const all = { ...buildFiles(), ...buildDiffs() };
  for (const [rel, text] of Object.entries(all)) {
    const target = path.join(OUT, rel);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, text);
  }
}

if (require.main === module) writeAll();
