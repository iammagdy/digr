const SECTOR_IDS: Record<string, string> = {};
const sectorOrder: string[] = [];
for (const row of rows) if (!(row.sector in SECTOR_IDS)) { sectorOrder.push(row.sector); SECTOR_IDS[row.sector] = `s${sectorOrder.length}`; }

const slugOf = (row: Row) => `${createHash("sha1").update(`${row.platform}|${row.key}|${row.idx}`).digest("hex").slice(0, 7)}`;

interface OutService { slug: string; nameAr: string; explainAr: string; group: string; core?: true }
interface OutPlatform { slug: string; nameAr: string; descAr: string; services: OutService[] }
interface OutSector { id: string; nameAr: string; descAr: string; platforms: OutPlatform[] }

const sectors: OutSector[] = [];
for (const sectorKey of sectorOrder) {
  const sectorMeta = meta.sectors[sectorKey];
  if (!sectorMeta) throw new Error(`no Arabic name for sector ${sectorKey}`);
  const platforms: OutPlatform[] = [];
  const platformOrder: string[] = [];
  for (const row of rows) if (row.sector === sectorKey && !platformOrder.includes(row.platform)) platformOrder.push(row.platform);
  for (const platformKey of platformOrder) {
    const platformMeta = meta.platforms[platformKey];
    if (!platformMeta) throw new Error(`no Arabic name for platform ${platformKey}`);
    const included = rows.filter((row) => row.platform === platformKey && (row.cls === "read" || row.cls === "core"));
    if (included.length === 0) continue;
    const byName = new Map<string, OutService>();
    for (const row of included) {
      const existing = byName.get(row.nameAr);
      if (existing) { if (row.cls === "core") existing.core = true; continue; }
      const explainAr = explanations[`${platformKey}|${row.nameAr}`];
      if (!explainAr) throw new Error(`no explanation for ${platformKey} | ${row.nameAr}`);
      byName.set(row.nameAr, { slug: slugOf(row), nameAr: row.nameAr, explainAr, group: row.group, ...(row.cls === "core" ? { core: true as const } : {}) });
    }
    const services = [...byName.values()].sort((a, b) => GROUP_ORDER.indexOf(a.group) - GROUP_ORDER.indexOf(b.group));
    platforms.push({ slug: platformKey, nameAr: platformMeta.nameAr, descAr: platformMeta.descAr, services });
  }
  sectors.push({ id: SECTOR_IDS[sectorKey], nameAr: sectorMeta.nameAr, descAr: sectorMeta.descAr, platforms });
}

