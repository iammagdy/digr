/**
 * Builds src/lib/servicesCatalog.ts (the ONE data module behind /services, the landing page and the chat's catalog map) from
 *   scripts/catalog/classification.json  one row per catalog line: the source's English label (never shown), its class and the Arabic name
 *   scripts/catalog/platforms.json       Arabic names and one-line descriptions of the sectors and platforms
 * Only the classes `read` and `core` are written to the module. `write`, `own`, `private` and `helper` lines are counted in
 * docs/services-catalog-classes.md and never reach the page. Service slugs are opaque hashes (the source's endpoint names never leave this script).
 *
 * Run: npx tsx scripts/build-services-catalog.ts
 */
