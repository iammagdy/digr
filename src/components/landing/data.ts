  const AR2 = (x: number) => toArabicDigits(x);
  const H = ["@unicef","@who","@natgeo","@redcross","@undp","@wfp","@unhcr","@aljazeera","@bbcarabic","@cairo.uni","@aucegypt","@egyptair","@amrdiab","@mosalah","@nasa","@unesco","@greenpeace","@savethechildren","@msf","@ted","@vogue.arabia","@forbesme","@skynewsarabia","@alahly","@zamalek","@talabat","@vodafone.eg","@orange.eg","@noon","@careem"];
