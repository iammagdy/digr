import { toArabicDigits } from "@/lib/arabicDigits";

/**
 * The records of the hero's blurred background. They are generic made-up lines (a kind of account, a count, a hashtag, a field name): no real
 * company, person, number or address. Seeded, so the same lines come out every time; built only in the browser, after the page is shown.
 */
export function buildFieldItems(): string[] {
  let seed = 20261011;
  const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296);
  const pick = <T,>(a: T[]): T => a[Math.floor(rnd() * a.length)];
  const n = (a: number, b: number) => Math.floor(a + rnd() * (b - a));
  const AR2 = (x: number) => toArabicDigits(x);
  const H = ["حساب منظمة دولية", "حساب إخباري", "حساب مجلة علمية", "حساب منظمة إغاثة", "حساب جامعة", "حساب شركة طيران", "حساب فنان", "حساب لاعب", "حساب وكالة فضاء", "حساب منظمة بيئية", "حساب مؤسسة تعليمية", "حساب قناة تلفزيونية", "حساب نادٍ رياضي", "حساب شركة توصيل", "حساب شركة اتصالات", "حساب متجر إلكتروني", "حساب مجلة أزياء", "حساب مؤسسة اقتصادية", "حساب مبادرة خيرية", "حساب مؤتمر"];
  const P = ["تيك توك", "يوتيوب", "إكس", "إنستجرام", "فيسبوك", "لينكدإن"];
  const T = ["#التعليم", "#الصحة_النفسية", "#المناخ", "#ريادة_الأعمال", "#كرة_القدم", "#رمضان", "#السياحة", "#الذكاء_الاصطناعي", "#المرأة", "#الشباب", "#القاهرة", "#التطوع", "#الأمن_الغذائي", "#الطاقة"];
  const F = ["المتابعون", "عدد المنشورات", "تاريخ النشر", "نص المنشور", "الوسوم", "المشاهدات", "الإعجابات", "التعليقات", "المشاركات", "رابط عام", "وصف الحساب", "موقع معلن", "لغة المحتوى", "مدة الفيديو"];
  const gens: Array<() => string> = [
    () => pick(H) + " · " + AR2(n(1, 980)) + (rnd() > 0.5 ? "ألف" : "م") + " متابع",
    () => "منشور " + AR2(n(1000, 99999)) + " · " + AR2(n(120, 90000)) + " إعجاب",
    () => "تعليق عام · " + AR2(n(1, 28)) + "/" + AR2(n(1, 12)) + "/" + AR2(n(2023, 2027)),
    () => "معدل التفاعل " + AR2(n(1, 9)) + "٫" + AR2(n(0, 9)) + "٪",
    () => AR2(n(40, 60000)) + " مشاركة",
    () => AR2(n(1, 900)) + "ألف مشاهدة",
    () => pick(T),
    () => pick(P) + " · " + pick(H),
    () => "سجل " + AR2(n(1, 1000)) + " / " + AR2(n(100, 1000)),
    () => pick(F) + ": " + pick(["نعم", "لا", "متاح", "غير متاح", "عام", AR2(n(1, 500))]),
    () => AR2(n(0, 23)) + ":" + AR2(n(10, 59)) + " · " + pick(P),
    () => pick(F) + " · " + pick(F),
    () => pick(["ملف سي إس في · جدول بيانات", "ملف إكسل · ورقتان", "ملف بي دي إف · ملخص تنفيذي", "دليل المتغيرات", "ملف بيانات · " + AR2(n(1, 40)) + " ك.ب"]),
    () => "آخر " + AR2(n(1, 12)) + " " + pick(["أشهر", "أسابيع", "أيام"]),
  ];
  const seen = new Set<string>();
  const out: string[] = [];
  while (out.length < 300) {
    const s = pick(gens)();
    if (!seen.has(s)) { seen.add(s); out.push(s); }
  }
  return out;
}
