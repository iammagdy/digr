import type { ArtifactEntry, RegistryArtifact } from "./artifact";
import type { MeasuredCalls } from "./evidence";

/**
 * PHASE 3, RELIABILITY AND COST EVIDENCE (task 3.4; audit PR-3.3). Diger's OWN execution, per endpoint and per operation, from the read-only aggregate of mission_calls in the registry artifact. Pure.
 *
 * Honest by construction:
 *   - a «usable response» is a call that RETURNED ROWS (status ok with rows_returned > 0); an HTTP 200 with no rows is not one, and an empty answer that was billed is counted separately (`emptyPaid`);
 *   - «validated rows» are NOT recorded per call (validation happens at delivery, per mission): the report says so instead of inventing a figure;
 *   - cost per row is per RETURNED row (a lower bound of the cost per usable, validated row);
 *   - the catalog's own success rate (TREG `observed`) is never used here: it is the provider's statistic, not Diger's.
 */
export interface EndpointReliability {
  id: string;
  operation: string;
  provider: string;
  level: string;
  attempts: number;
  usableResponses: number;
  usableShare: number | null;
  emptyPaid: number;
  failed: number;
  refused: number;
  rowsReturned: number;
  costUsd: number;
  costPerReturnedRow: number | null;
  p50Ms: number | null;
}

export interface OperationReliability {
  operation: string;
  endpointsMeasured: number;
  attempts: number;
  usableResponses: number;
  usableShare: number | null;
  emptyPaid: number;
  rowsReturned: number;
  costUsd: number;
  costPerReturnedRow: number | null;
}

export interface ReliabilityReport {
  endpoints: EndpointReliability[];
  operations: OperationReliability[];
  /** Measured endpoints the registry does not map to any operation (outside discovery). */
  unmapped: string[];
  totals: { attempts: number; usableResponses: number; emptyPaid: number; costUsd: number };
}

const r6 = (n: number) => Number(n.toFixed(6));
const share = (a: number, b: number): number | null => (b > 0 ? Number((a / b).toFixed(3)) : null);

export function reliabilityReport(a: RegistryArtifact, snapshotIds: ReadonlyArray<string>): ReliabilityReport {
  const byId = new Map<string, ArtifactEntry[]>();
  for (const c of a.capabilities) byId.set(c.id, [...(byId.get(c.id) ?? []), c]);
  const endpoints: EndpointReliability[] = [];
  for (const c of a.capabilities) {
    const m: MeasuredCalls | null = c.reliability.diger;
    if (!m || m.attempts + m.refused === 0) continue;
    endpoints.push({
      id: c.id, operation: c.operation, provider: c.sub_provider, level: c.verification.level, attempts: m.attempts, usableResponses: m.withRows, usableShare: share(m.withRows, m.attempts), emptyPaid: m.emptyPaid, failed: m.failed, refused: m.refused,
      rowsReturned: m.rows, costUsd: r6(m.costUsd), costPerReturnedRow: m.rows > 0 ? r6(m.costUsd / m.rows) : null, p50Ms: m.p50Ms,
    });
  }
  endpoints.sort((x, y) => x.operation.localeCompare(y.operation) || y.attempts - x.attempts || x.id.localeCompare(y.id));
  const ops = new Map<string, OperationReliability>();
  const seen = new Set<string>();
  for (const e of endpoints) {
    // an endpoint that serves two operations (a parser) is counted once per operation; totals count it once
    const o = ops.get(e.operation) ?? { operation: e.operation, endpointsMeasured: 0, attempts: 0, usableResponses: 0, usableShare: null, emptyPaid: 0, rowsReturned: 0, costUsd: 0, costPerReturnedRow: null };
    o.endpointsMeasured += 1; o.attempts += e.attempts; o.usableResponses += e.usableResponses; o.emptyPaid += e.emptyPaid; o.rowsReturned += e.rowsReturned; o.costUsd = r6(o.costUsd + e.costUsd);
    ops.set(e.operation, o);
    seen.add(e.id);
  }
  const operations = [...ops.values()].map((o) => ({ ...o, usableShare: share(o.usableResponses, o.attempts), costPerReturnedRow: o.rowsReturned > 0 ? r6(o.costUsd / o.rowsReturned) : null })).sort((x, y) => x.operation.localeCompare(y.operation));
  const once = [...seen].map((id) => byId.get(id)![0].reliability.diger!);
  return {
    endpoints, operations,
    unmapped: snapshotIds.filter((id) => !byId.has(id)).sort(),
    totals: { attempts: once.reduce((n, m) => n + m.attempts, 0), usableResponses: once.reduce((n, m) => n + m.withRows, 0), emptyPaid: once.reduce((n, m) => n + m.emptyPaid, 0), costUsd: r6(once.reduce((n, m) => n + m.costUsd, 0)) },
  };
}

const cell = (v: unknown): string => (v === null || v === undefined ? "–" : String(v));

/** The report as reviewable Markdown (deterministic). */
export function reliabilityMarkdown(r: ReliabilityReport, through: string): string {
  const lines: string[] = [
    "# Diger's own provider reliability and cost (generated)",
    "",
    `GENERATED by \`scripts/capabilities/reliability-report.ts\` from \`data/capabilities/registry.json\` (Diger's recorded calls through ${through}, \`data/capabilities/reliability-snapshot.json\`). Do not edit by hand.`,
    "",
    "* A **usable response** is a call that returned rows. An HTTP 200 with no rows is not one; an empty answer that was billed is counted in **empty paid**.",
    "* **Validated rows are not recorded per call** (validation happens at delivery, per mission), so no validated-row figure is given.",
    "* **Cost per row** is per RETURNED row: a lower bound of the cost per usable, validated row.",
    "* The provider catalog's own success rates are NOT used: they are the provider's statistic, not Diger's.",
    "* The calls include evaluation and test-account missions.",
    "",
    `**Totals (registry-mapped endpoints):** ${r.totals.attempts} calls reached a provider, ${r.totals.usableResponses} returned rows, ${r.totals.emptyPaid} empty answers were billed, $${r.totals.costUsd} recorded.`,
    "",
    "## By operation",
    "",
    "| Operation | Endpoints measured | Calls | Usable | Usable share | Empty paid | Rows returned | USD | USD per returned row |",
    "|---|---|---|---|---|---|---|---|---|",
    ...r.operations.map((o) => `| ${o.operation} | ${o.endpointsMeasured} | ${o.attempts} | ${o.usableResponses} | ${cell(o.usableShare)} | ${o.emptyPaid} | ${o.rowsReturned} | ${o.costUsd} | ${cell(o.costPerReturnedRow)} |`),
    "",
    "## By endpoint",
    "",
    "| Operation | Endpoint | Level | Calls | Usable | Share | Empty paid | Failed | Refused | Rows | USD | USD/row | p50 ms |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ...r.endpoints.map((e) => `| ${e.operation} | \`${e.id}\` | ${e.level} | ${e.attempts} | ${e.usableResponses} | ${cell(e.usableShare)} | ${e.emptyPaid} | ${e.failed} | ${e.refused} | ${e.rowsReturned} | ${e.costUsd} | ${cell(e.costPerReturnedRow)} | ${cell(e.p50Ms)} |`),
    "",
    "## Measured endpoints outside the registry",
    "",
    "Recorded calls of endpoints that map to no data operation (contact finders and verifiers of the people path, channel searches, unrelated tools). They are not discovery candidates:",
    "",
    r.unmapped.map((id) => `\`${id}\``).join(", "),
    "",
  ];
  return lines.join("\n");
}
