import type { BenchmarkResult } from "./extractionBenchmark";
import { totals } from "./extractionBenchmark";

export interface Baseline { recordedFrom: string; results: BenchmarkResult[] }

const pct = (n: number, d: number) => (d ? `${Math.round((n / d) * 100)}%` : "—");

/** The committed benchmark document: the table after the change, with the recorded numbers from before it. */
export function renderBenchmarkMarkdown(results: BenchmarkResult[], baseline: Baseline | null): string {
  const before = new Map((baseline?.results || []).map((r) => [r.capability, r]));
  const rows = results.map((r) => {
    const b = before.get(r.capability);
    return `| ${r.capability} | ${r.rowsIn} | ${r.duplicates} | ${r.delivered} | ${r.review} | ${r.rejected} | ${r.agreement}/${r.rowsIn} (${pct(r.agreement, r.rowsIn)}) | ${r.falseDeliveries} | ${r.lostMatches} | ${r.latinHeaders.length} | ${r.formatIssues} | ${b ? `${b.agreement}/${b.rowsIn}, wrong ${b.falseDeliveries}, lost ${b.lostMatches}` : "—"} |`;
  });
  const t = totals(results);
  const bt = baseline ? totals(baseline.results) : null;
  const people = results.find((r) => r.people);
  return `# Extraction benchmark

Generated by \`npx tsx scripts/extraction-benchmark.ts --write\` from the saved raw rows in \`tests/fixtures/extraction\`.
Offline: no database, no provider call, no spend. Each fixture row carries the outcome a reviewer expects
(delivered / review / rejected / duplicate); "agreement" counts rows whose outcome equals it.

- **Delivered** = passes the gate and is charged. **Review** = uncertain: goes to the review sheet, never charged.
  **Rejected** = excluded, never charged. **Duplicates** = repeats across pages, dropped before the gate.
- **False deliveries** = delivered although a reviewer expected review, rejection or a duplicate (a wrong charge).
  **Lost matches** = expected delivery that was not delivered.
- **Latin headers / format issues** are measured on the real delivered Excel (header cells with Latin letters; dates that are
  not a plain date; count cells that are not numbers).

| Capability | Rows in | Duplicates | Delivered | Review | Rejected | Agreement (after) | False deliveries | Lost matches | Latin headers | Format issues | Before this change |
|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}
| **Total** | ${t.rowsIn} | ${t.duplicates} | ${t.delivered} | ${t.review} | ${t.rejected} | ${t.agreement}/${t.rowsIn} (${pct(t.agreement, t.rowsIn)}) | ${t.falseDeliveries} | ${t.lostMatches} | | | ${bt ? `${bt.agreement}/${bt.rowsIn}, wrong ${bt.falseDeliveries}, lost ${bt.lostMatches}` : "—"} |

"Before this change" is recorded from ${baseline?.recordedFrom ?? "n/a"}: agreement, false deliveries (wrong) and lost matches (lost).
${people?.people ? `
## Decision makers: field by field

Requested fields: work email and phone. Charged units from the delivered rows: base person ${people.people.baseUnits}, work email ${people.people.emailUnits}, phone ${people.people.phoneUnits}
(${people.people.chargePoints} points); delivered rows with no requested field, charged nothing: ${people.people.notChargedRows}.
` : ""}
Read these numbers for what they are: the rows are synthetic (made up, no personal data) and modelled on the provider shapes
seen in production, and the rules were tuned against them, so a perfect score here proves the rules behave as written and
guards against regressions; it is not a measured accuracy on real customer data. The "before" column used the same rows.
Add a fixture row whenever a real rejection or miss is found, then re-run the script and commit the new table.

Not covered offline: the date window a customer names (filtered before the gate), and trending-video upload age, which by
design never rejects a row (upload age is not trend age; the region-scoped feed is the evidence).
`;
}
